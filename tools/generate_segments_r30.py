def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    bad = False
    for s in SEGMENTS:
        for label, text, lo, hi in (
            ("title", s["title"], 12, 40),
            ("desc", s["desc"], 60, 130),
        ):
            if not lo <= len(text) <= hi:
                print(f"{s['slug']} {label} {len(text)}: {text}", file=sys.stderr)
                bad = True
    if bad:
        return 1

    for s in SEGMENTS:
        path = PUBLIC / "specialty" / s["slug"] / "index.html"
        if args.check:
            print(("ok " if path.exists() else "missing ") + str(path))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(build_page(s), encoding="utf-8")
        print("wrote", path.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
