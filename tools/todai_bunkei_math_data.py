YEARS = list(range(1977, 2027))


def records() -> list[dict]:
    out = []
    for year, q, label, domains, diff, shared, src in RECORDS:
        out.append(
            {
                "year": year,
                "q": q,
                "label": label,
                "domains": domains,
                "primary": domains[0],
                "difficulty": diff,
                "shared": shared,
                "sources": src,
            }
        )
    return out


def validate() -> list[str]:
    """年度×大問が4件ずつ、分野タグが語彙内にあることを確かめる。"""
    errors: list[str] = []
    seen: dict[int, set[int]] = {}
    for year, q, _label, domains, diff, _shared, src in RECORDS:
        seen.setdefault(year, set()).add(q)
        if not domains:
            errors.append(f"{year} 第{q}問: 分野タグが空")
        for d in domains:
            if d not in DOMAIN_NAMES and d != "論証":
                errors.append(f"{year} 第{q}問: 未知の分野タグ {d}")
        if diff not in ("標準", "やや難", "難"):
            errors.append(f"{year} 第{q}問: 難易度 {diff}")
        for s in src:
            if s not in {x["id"] for x in SOURCES}:
                errors.append(f"{year} 第{q}問: 未知の出典 {s}")
    for year in YEARS:
        got = sorted(seen.get(year, set()))
        if got != [1, 2, 3, 4]:
            errors.append(f"{year}: 大問 {got}")
    if len(RECORDS) != 200:
        errors.append(f"records {len(RECORDS)} != 200")
    return errors


def payload() -> dict:
    rows = records()
    return {
        "dataset": {
            "name": "東大文系数学 過去問データベース（1977〜2026年）",
            "publisher": "黒田塾（黒田清友）",
            "url": "https://kurodaschool.jp/data/todai-bunkei-math-50years/",
            "coverage": "1977-2026",
            "years": len(YEARS),
            "questions": len(rows),
            "updated": UPDATED,
            "note": (
                "年度・大問番号・出題分野のみを収録し、問題文は転載していない。"
                "難易度は黒田塾の編集上の目安で、正答率などのデータではない。"
            ),
            "license": "出題内容の事実は東京大学の入試問題に基づく。分野分類と難易度は黒田塾の整理。",
        },
        "domains": [{"name": n, "description": d} for n, d in DOMAINS] + [
            {"name": "論証", "description": "証明・論証が主題の出題（他分野にまたがる補助タグ）。"}
        ],
        "sources": SOURCES,
        "records": rows,
    }


def write_json(path: Path) -> str:
    text = json.dumps(payload(), ensure_ascii=False, indent=1) + "\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return text


def write_csv(path: Path) -> str:
    lines = ["年度,大問,出題分野（主）,分野タグ,難易度の目安,文理共通,出題内容の要約"]
    for r in records():
        tags = "／".join(r["domains"])
        label = r["label"].replace(",", "、")
        lines.append(
            f"{r['year']},{r['q']},{r['primary']},{tags},{r['difficulty']},"
            f"{r['shared'] or '—'},{label}"
        )
    text = "\n".join(lines) + "\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return text


