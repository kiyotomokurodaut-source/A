def build_page(art: dict, template: str) -> str:
    old_title = re.search(r"<title>(.*?)</title>", template).group(1)
    old_desc = re.search(r'<meta content="([^"]*)" name="description"/>', template).group(1)
    old_path = "/study-guides/mock-e-hantei-recovery/"
    old_url = SITE + old_path
    new_url = f"{SITE}/study-guides/{art['slug']}/"

    head = template[: template.find("<main")]
    head = head.replace(old_title, art["title"]).replace(old_desc, art["description"])
    head = head.replace(old_url, new_url)
    head = re.sub(r'<meta content="\d{4}-\d{2}-\d{2}" name="last-modified"/>',
                  f'<meta content="{TODAY}" name="last-modified"/>', head)
    head = re.sub(r'<script type="application/ld\+json">.*?</script>',
                  lambda m: f'<script type="application/ld+json">{ld_json(art)}</script>',
                  head, count=1, flags=re.S)

    footer = template[template.find("<footer>"):]
    cut = footer.find('<a class="r27-sticky"')
    if cut > 0:
        footer = footer[:cut]
    footer = footer.replace("</body></html>", "").rstrip()
    return head + article_body(art) + footer + "</body></html>\n"


